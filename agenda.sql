-- AGENDA (aba Agenda do painel: a sua rotina da semana)
--
-- ONDE COLAR: Supabase > SQL Editor > New query > cole tudo > Run.
-- Se aparecer o aviso "Potential issue detected", clique em "Run query":
-- ele aparece por causa do "drop policy if exists", que só troca a regra
-- antiga pela nova. Nada é apagado. Pode rodar mais de uma vez.
-- =========================================================

-- Um compromisso por linha.
--   dias preenchido  = rotina fixa, repete toda semana (0 = segunda ... 6 = domingo)
--   dias vazio       = compromisso de uma vez só, no dia do campo "data"
create table if not exists public.agenda (
  id           bigint generated by default as identity primary key,
  criado_em    timestamptz not null default now(),
  titulo       text not null default '',
  categoria    text not null default 'rotina'
               check (categoria in ('rotina', 'exercicio', 'trabalho', 'igreja', 'casa', 'cuidar')),
  dias         smallint[] not null default '{}',
  data         date,
  hora_inicio  smallint not null default 8  check (hora_inicio between 0 and 23),
  hora_fim     smallint not null default 9  check (hora_fim between 1 and 24),
  pulos        date[] not null default '{}',   -- dias em que a rotina não vai acontecer
  obs          text not null default '',
  exemplo      boolean not null default false,
  check (hora_fim > hora_inicio)
);
create index if not exists agenda_data_idx on public.agenda (data);

-- A tranca: só você, logada, lê e escreve. Ninguém de fora vê nada.
alter table public.agenda enable row level security;
revoke all on public.agenda from anon;
grant select, insert, update, delete on public.agenda to authenticated;

drop policy if exists "dona faz tudo" on public.agenda;
create policy "dona faz tudo" on public.agenda
  for all to authenticated
  using ((select privado.sou_eu())) with check ((select privado.sou_eu()));

notify pgrst, 'reload schema';
