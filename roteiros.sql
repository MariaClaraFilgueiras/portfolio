-- Um roteiro por linha. Com data, ele aparece sozinho no Calendário.
create table if not exists public.roteiros (
  id         bigint generated by default as identity primary key,
  criado_em  timestamptz not null default now(),
  rede       text not null default 'tiktok' check (rede in ('tiktok', 'instagram')),
  titulo     text not null default '',
  data       date,                                   -- o dia do post (vazio = ideia sem data)
  status     text not null default 'ideia'
             check (status in ('ideia', 'roteiro', 'gravado', 'editado', 'postado')),
  formato    text not null default '',               -- Reels, Carrossel, Stories, Vídeo...
  roteiro    text not null default '',               -- o texto do roteiro
  legenda    text not null default '',               -- a legenda do post
  link       text not null default '',               -- o link depois de postado
  exemplo    boolean not null default false
);
create index if not exists roteiros_data_idx on public.roteiros (data);

-- No Instagram, cada roteiro fica no quadro do Feed ou no dos Stories
alter table public.roteiros add column if not exists quadro text not null default 'feed';
alter table public.roteiros drop constraint if exists roteiros_quadro_check;
alter table public.roteiros add constraint roteiros_quadro_check check (quadro in ('feed', 'stories'));

-- A tranca: só você, logada, lê e escreve. Ninguém de fora vê nada.
alter table public.roteiros enable row level security;
revoke all on public.roteiros from anon;
grant select, insert, update, delete on public.roteiros to authenticated;

drop policy if exists "dona faz tudo" on public.roteiros;
create policy "dona faz tudo" on public.roteiros
  for all to authenticated
  using ((select privado.sou_eu())) with check ((select privado.sou_eu()));

