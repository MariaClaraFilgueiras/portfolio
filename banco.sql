  criador      text not null default '',   -- o @ de quem fez o vídeo
  transcricao  text not null default '',   -- o roteiro que você colou
  observacoes  text not null default '',
  exemplo      boolean not null default false
);

alter table public.transcricoes enable row level security;
revoke all on public.transcricoes from anon;
